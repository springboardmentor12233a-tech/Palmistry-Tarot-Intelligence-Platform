def generate_excel_report(reading: FullReading, user_name: str = "Seeker") -> bytes:
    """Generates a structured, multi-tab Excel workbook as raw bytes."""
    wb = openpyxl.Workbook()

    # Style constants
    header_fill = PatternFill(start_color="3D2C6A", end_color="3D2C6A", fill_type="solid")
    header_font = Font(name="Arial", size=11, bold=True, color="FFFFFF")
    title_font = Font(name="Arial", size=14, bold=True, color="2C1E4E")
    bold_font = Font(name="Arial", size=10, bold=True)
    normal_font = Font(name="Arial", size=10)
    thin_border = Border(
        left=Side(style="thin", color="E0DFE8"),
        right=Side(style="thin", color="E0DFE8"),
        top=Side(style="thin", color="E0DFE8"),
        bottom=Side(style="thin", color="E0DFE8"),
    )

    # -------------------------------------------------------------
    # Sheet 1: Overview
    # -------------------------------------------------------------
    ws1 = wb.active
    ws1.title = "Overview"

    ws1["A1"] = "Palmistry & Tarot Intelligence Report"
    ws1["A1"].font = title_font
    ws1.append([])

    overview_rows = [
        ("Reading ID", reading.id),
        ("Seeker Name", user_name),
        ("Date Generated", reading.date),
        ("Spread Type", reading.spread_type),
        ("Spread Title", reading.spread_title),
        ("Overall Insight Score", f"{reading.insight_score.overall}%"),
        ("Synthesis Tier", reading.insight_score.tier),
        ("Palm Confidence Sub-Score", f"{reading.insight_score.palm_confidence}%"),
        ("Tarot Relevance Sub-Score", f"{reading.insight_score.tarot_relevance}%"),
        ("Personality Alignment Sub-Score", f"{reading.insight_score.personality_alignment}%"),
        ("Context Relevance Sub-Score", f"{reading.insight_score.context_relevance}%"),
        ("Consistency Sub-Score", f"{reading.insight_score.consistency}%"),
    ]

    for label, val in overview_rows:
        ws1.append([label, str(val)])

    ws1.append([])
    ws1.append(["Executive Narrative Summary"])
    ws1.append([reading.interpretation.overview_summary])

    # -------------------------------------------------------------
    # Sheet 2: Palm Biometrics
    # -------------------------------------------------------------
    ws2 = wb.create_sheet("Palm Biometrics")
    ws2.append(["Line Name", "Length", "Depth", "Curvature", "Confidence", "Interpretation Summary"])
    for cell in ws2[1]:
        cell.fill = header_fill
        cell.font = header_font

    lines = [
        ("Heart Line", reading.palm_result.lines.heart_line),
        ("Head Line", reading.palm_result.lines.head_line),
        ("Life Line", reading.palm_result.lines.life_line),
    ]
    if reading.palm_result.lines.fate_line:
        lines.append(("Fate Line", reading.palm_result.lines.fate_line))

    for name, line_data in lines:
        ws2.append([
            name,
            line_data.length,
            line_data.depth,
            line_data.curvature,
            f"{line_data.confidence}%",
            line_data.summary,
        ])

    # -------------------------------------------------------------
    # Sheet 3: Tarot Spread
    # -------------------------------------------------------------
    ws3 = wb.create_sheet("Tarot Spread")
    ws3.append(["Position Index", "Position Label", "Position Meaning", "Card Name", "Orientation", "Arcana", "Suit", "Keywords", "Archetypal Meaning"])
    for cell in ws3[1]:
        cell.fill = header_fill
        cell.font = header_font

    for card_drawn in reading.tarot_result.cards:
        c = card_drawn.card
        meaning_text = c.reversed_meaning if card_drawn.is_reversed else c.upright_meaning
        ws3.append([
            card_drawn.position_index + 1,
            card_drawn.position_label,
            card_drawn.position_meaning,
            c.name,
            "Reversed" if card_drawn.is_reversed else "Upright",
            c.arcana,
            c.suit or "Trump",
            ", ".join(c.keywords),
            meaning_text,
        ])

    # -------------------------------------------------------------
    # Sheet 4: Categories & Recommendations
    # -------------------------------------------------------------
    ws4 = wb.create_sheet("Guidance & Actions")
    ws4.append(["Category Title", "Score", "Summary Narrative", "Key Takeaways"])
    for cell in ws4[1]:
        cell.fill = header_fill
        cell.font = header_font

    for cat in reading.interpretation.categories:
        ws4.append([
            cat.title,
            f"{cat.score}%",
            cat.detailed_narrative,
            " | ".join(cat.key_takeaways),
        ])

    # Auto-adjust column widths
    for ws in [ws1, ws2, ws3, ws4]:
        for col in ws.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws.column_dimensions[col_letter].width = min(max_len + 4, 60)

    output = io.BytesIO()
    wb.save(output)
    return output.getvalue()
