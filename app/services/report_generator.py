class PDFReport(FPDF):
    """Styled PDF Generator for Palmistry & Tarot Intelligence Platform."""

    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(120, 110, 140)
        self.cell(0, 8, "PALMISTRY & TAROT INTELLIGENCE PLATFORM", border=0, align="L")
        self.cell(0, 8, "CONFIDENTIAL & SACRED", border=0, align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(220, 215, 230)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 145, 160)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}} - Generated by Cosmic Oracle AI", align="C")


def clean_text(text: Optional[str]) -> str:
    """Sanitizes text for standard Latin-1 PDF encoding."""
    if not text:
        return ""
    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2013": "-",
        "\u2014": "--",
        "\u2022": "-",
        "\u2026": "...",
        "\u00a0": " ",
    }
    for orig, rep in replacements.items():
        text = text.replace(orig, rep)
    # Ensure text is encodable in latin-1
    return text.encode("latin-1", "replace").decode("latin-1")


